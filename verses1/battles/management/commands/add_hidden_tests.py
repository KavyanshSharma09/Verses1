class Command(BaseCommand):
    help = 'Add extra hidden test cases to existing problems'

    def handle(self, *args, **options):
        self.stdout.write('Adding extra hidden test cases...')
        
        total_added = 0
        for slug, test_cases in EXTRA_HIDDEN_TESTS.items():
            try:
                problem = ProblemStatement.objects.get(slug=slug)
                existing_count = problem.test_cases.count()
                
                for i, tc in enumerate(test_cases):
                    # Check if test case already exists
                    exists = TestCase.objects.filter(
                        problem=problem,
                        input_data=tc['input']
                    ).exists()
                    
                    if not exists:
                        TestCase.objects.create(
                            problem=problem,
                            input_data=tc['input'],
                            expected_output=tc['output'],
                            is_hidden=True,
                            is_sample=False,
                            order=existing_count + i + 1,
                            points=10
                        )
                        total_added += 1
                
                new_count = problem.test_cases.count()
                added = new_count - existing_count
                if added > 0:
                    self.stdout.write(f'  {problem.title}: Added {added} hidden test cases (total: {new_count})')
                else:
                    self.stdout.write(f'  {problem.title}: No new test cases added (already has {existing_count})')
                    
            except ProblemStatement.DoesNotExist:
                self.stdout.write(self.style.WARNING(f'  Problem not found: {slug}'))
        
        self.stdout.write(self.style.SUCCESS(f'\nDone! Added {total_added} new hidden test cases.'))
